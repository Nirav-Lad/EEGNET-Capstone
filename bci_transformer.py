# --- Transformer Encoder Block ---
def transformer_encoder(inputs, head_size, num_heads, ff_dim, dropout=0):
    # Attention and Normalization
    x = MultiHeadAttention(key_dim=head_size, num_heads=num_heads, dropout=dropout)(inputs, inputs)
    x = Dropout(dropout)(x)
    x = LayerNormalization(epsilon=1e-6)(x + inputs)

    # Feed Forward Part
    ffn = tf.keras.Sequential([
        Dense(ff_dim, activation="relu"),
        Dense(inputs.shape[-1]),
    ])
    x = ffn(x)
    x = Dropout(dropout)(x)
    x = LayerNormalization(epsilon=1e-6)(x)
    return x

# --- Build the Full Model ---
def build_transformer_model(input_shape, head_size, num_heads, ff_dim, num_transformer_blocks, num_classes, dropout=0):
    inputs = Input(shape=input_shape)
    x = inputs

    # Create multiple Transformer Encoder blocks
    for _ in range(num_transformer_blocks):
        x = transformer_encoder(x, head_size, num_heads, ff_dim, dropout)

    # Global Average Pooling to reduce the sequence to a single feature vector
    x = GlobalAveragePooling1D(data_format="channels_last")(x)

    # Final Classification Head
    x = Dropout(0.4)(x)
    x = Dense(20, activation="relu")(x)
    outputs = Dense(num_classes, activation="softmax")(x)

    return Model(inputs, outputs)

